# Generates the faceted low-poly pieces the trees are built from, as OBJ files:
#   Clump_A/B/C  - an irregular, flat-shaded leaf clump (jittered icosphere, 80 faces), 100 cm across
#   Limb         - a tapered six-sided trunk/branch segment, 100 cm tall, 100 cm wide at the base, 55% at the top
#   PineTier     - a jittered faceted cone, 100 cm wide, 100 cm tall, for pine trees
# Usage: powershell -File gen_foliage_meshes.ps1 <output folder>
# Units are centimetres, Z up (the importer is told the files are Z-up).
param([string]$OutDir = ".")

$ErrorActionPreference = "Stop"
New-Item -ItemType Directory -Force $OutDir | Out-Null
$inv = [System.Globalization.CultureInfo]::InvariantCulture

function Fmt([double]$v) { return $v.ToString("0.#####", $inv) }

# Writes a flat-shaded OBJ: every face gets its own normal, so facets read like the kit's plants.
function Write-Obj([string]$Path, $Verts, $Faces) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("# generated by gen_foliage_meshes.ps1")
    foreach ($v in $Verts) { [void]$sb.AppendLine("v $(Fmt $v[0]) $(Fmt $v[1]) $(Fmt $v[2])") }
    $n = 1
    foreach ($f in $Faces) {
        $a = $Verts[$f[0]]; $b = $Verts[$f[1]]; $c = $Verts[$f[2]]
        $ux = $b[0]-$a[0]; $uy = $b[1]-$a[1]; $uz = $b[2]-$a[2]
        $vx = $c[0]-$a[0]; $vy = $c[1]-$a[1]; $vz = $c[2]-$a[2]
        $nx = $uy*$vz - $uz*$vy; $ny = $uz*$vx - $ux*$vz; $nz = $ux*$vy - $uy*$vx
        $len = [Math]::Sqrt($nx*$nx + $ny*$ny + $nz*$nz); if ($len -lt 1e-9) { $len = 1 }
        [void]$sb.AppendLine("vn $(Fmt ($nx/$len)) $(Fmt ($ny/$len)) $(Fmt ($nz/$len))")
        [void]$sb.AppendLine("vt 0.5 0.5")
        [void]$sb.AppendLine("f $($f[0]+1)/1/$n $($f[1]+1)/1/$n $($f[2]+1)/1/$n")
        $n++
    }
    # vt lines are interleaved above; OBJ allows any order, all faces use vt index 1.
    Set-Content -Path $Path -Value $sb.ToString() -Encoding ASCII
}

# Icosphere, subdivided once: 42 vertices, 80 faces.
function New-IcoSphere {
    $t = (1 + [Math]::Sqrt(5)) / 2
    $v = New-Object System.Collections.ArrayList
    foreach ($p in @(@(-1,$t,0),@(1,$t,0),@(-1,-$t,0),@(1,-$t,0),@(0,-1,$t),@(0,1,$t),@(0,-1,-$t),@(0,1,-$t),@($t,0,-1),@($t,0,1),@(-$t,0,-1),@(-$t,0,1))) {
        $l = [Math]::Sqrt($p[0]*$p[0]+$p[1]*$p[1]+$p[2]*$p[2]); [void]$v.Add(@(($p[0]/$l),($p[1]/$l),($p[2]/$l)))
    }
    $f = @(@(0,11,5),@(0,5,1),@(0,1,7),@(0,7,10),@(0,10,11),@(1,5,9),@(5,11,4),@(11,10,2),@(10,7,6),@(7,1,8),
           @(3,9,4),@(3,4,2),@(3,2,6),@(3,6,8),@(3,8,9),@(4,9,5),@(2,4,11),@(6,2,10),@(8,6,7),@(9,8,1))
    $cache = @{}
    $mid = {
        param($i, $j)
        $key = if ($i -lt $j) { "$i-$j" } else { "$j-$i" }
        if ($cache.ContainsKey($key)) { return $cache[$key] }
        $a = $v[$i]; $b = $v[$j]
        $m = @((($a[0]+$b[0])/2),(($a[1]+$b[1])/2),(($a[2]+$b[2])/2))
        $l = [Math]::Sqrt($m[0]*$m[0]+$m[1]*$m[1]+$m[2]*$m[2])
        [void]$v.Add(@(($m[0]/$l),($m[1]/$l),($m[2]/$l)))
        $cache[$key] = $v.Count - 1
        return $v.Count - 1
    }
    $faces = New-Object System.Collections.ArrayList
    foreach ($tri in $f) {
        $a = & $mid $tri[0] $tri[1]; $b = & $mid $tri[1] $tri[2]; $c = & $mid $tri[2] $tri[0]
        [void]$faces.Add(@($tri[0],$a,$c)); [void]$faces.Add(@($tri[1],$b,$a)); [void]$faces.Add(@($tri[2],$c,$b)); [void]$faces.Add(@($a,$b,$c))
    }
    return ,@($v, $faces)
}

# Leaf clumps: jitter each vertex's radius, flatten the underside a little.
foreach ($spec in @(@("A", 11), @("B", 23), @("C", 37))) {
    $rng = New-Object System.Random($spec[1])
    $ico = New-IcoSphere
    $verts = @()
    foreach ($p in $ico[0]) {
        $r = 50 * (0.82 + 0.3 * $rng.NextDouble())
        $z = $p[2]
        if ($z -lt 0) { $z = $z * 0.7 }   # flatter bottom, like a real canopy
        $verts += ,@(($p[0]*$r), ($p[1]*$r), ($z*$r*0.92))
    }
    Write-Obj (Join-Path $OutDir "Clump_$($spec[0]).obj") $verts $ico[1]
}

# Limb: tapered hexagonal frustum from z=0 (radius 50) to z=100 (radius 27.5), capped.
$sides = 6
$verts = @(); $faces = @()
for ($i = 0; $i -lt $sides; $i++) {
    $a = 2 * [Math]::PI * $i / $sides
    $verts += ,@((50*[Math]::Cos($a)), (50*[Math]::Sin($a)), 0)
}
for ($i = 0; $i -lt $sides; $i++) {
    $a = 2 * [Math]::PI * ($i + 0.5) / $sides
    $verts += ,@((27.5*[Math]::Cos($a)), (27.5*[Math]::Sin($a)), 100)
}
$verts += ,@(0,0,0); $verts += ,@(0,0,100)
$cb = 2*$sides; $ct = 2*$sides+1
for ($i = 0; $i -lt $sides; $i++) {
    $j = ($i + 1) % $sides
    $faces += ,@($i, $j, ($sides+$i))
    $faces += ,@($j, ($sides+$j), ($sides+$i))
    $faces += ,@($j, $i, $cb)
    $faces += ,@(($sides+$i), ($sides+$j), $ct)
}
Write-Obj (Join-Path $OutDir "Limb.obj") $verts $faces

# Pine tier: 9-sided drooping cone. Jittered rim at the bottom, a slightly bulging mid ring,
# a tip, and a shallow concave underside up to a centre point.
$rng = New-Object System.Random(53)
$sides = 9
$verts = @(); $faces = @()
for ($i = 0; $i -lt $sides; $i++) {
    $a = 2 * [Math]::PI * ($i + 0.25 * $rng.NextDouble()) / $sides
    $r = 50 * (0.85 + 0.2 * $rng.NextDouble())
    $verts += ,@(($r*[Math]::Cos($a)), ($r*[Math]::Sin($a)), (6 * $rng.NextDouble()))
}
for ($i = 0; $i -lt $sides; $i++) {
    $a = 2 * [Math]::PI * ($i + 0.5) / $sides
    $r = 31 * (0.92 + 0.16 * $rng.NextDouble())
    $verts += ,@(($r*[Math]::Cos($a)), ($r*[Math]::Sin($a)), 42)
}
$verts += ,@(0,0,100)
$verts += ,@(0,0,18)
$tip = 2*$sides; $under = 2*$sides+1
for ($i = 0; $i -lt $sides; $i++) {
    $j = ($i + 1) % $sides
    # outer surface: rim -> mid ring -> tip (counter-clockwise seen from outside)
    $faces += ,@($i, $j, ($sides+$i))
    $faces += ,@($j, ($sides+$j), ($sides+$i))
    $faces += ,@(($sides+$i), ($sides+$j), $tip)
    # underside: rim -> centre, facing down
    $faces += ,@($j, $i, $under)
}
Write-Obj (Join-Path $OutDir "PineTier.obj") $verts $faces

Write-Output "wrote $(Get-ChildItem $OutDir -Filter *.obj | Measure-Object | Select-Object -ExpandProperty Count) OBJ files to $OutDir"
